// Package update — 自动更新的纯逻辑核心：查版本 / 下载 / 校验 / 替换 / 重启。
//
// 正交意图（3 个，2026-11-13 kzf 需求：「自动下载更新，点击能做到更新替换文件
// 并自动重启恢复服务」「下载能力与 npm-js 保持一致」「设置里可关闭」「可手动检查」）：
//
//  1. 版本与产物的「事实」只来自 GitHub Release，不在本地维护版本表
//  2. 下载契约与 npm 引导器逐条等价（镜像前缀 / 断点续传 / .part 原子落盘）
//  3. 自我替换是一条「宁可不更新，也不能变砖」的路径——每一道都能单独中止
//
// 本包**不做** UI、不读用户设置文件、不判断「要不要自动更新」。开关、频率、
// 是否静默，都是调用方（GUI / CLI）的事。这里只回答「有没有新版」「怎么安全换掉」。
//
// # 镜像契约（三处共用的唯一信源：npm/lib/mirror.js / 本包 / GUI 设置页）
//
// 优先级只有两档，刻意不加第三档（如 GH_PROXY）——共享契约每多一层，三处
// 漂移的概率就多一份：
//
//  1. 显式传入的 Options.Mirrors（非 nil）      ← GUI 设置页保存的值
//  2. 环境变量 REPLY9842_MIRROR                ← 命令行 / CI 临时覆盖
//  3. 内置 DefaultMirrors                      ← 未配置时的默认行为
//
// 「未设置」与「设置为空」语义不同：前者用默认列表，后者是「用户显式要求直连」。
// 所以内部一律用 os.LookupEnv 判断存在性，不用 os.Getenv()==""。
// 切分、trim、direct、补斜杠、去重等逐条规则见 mirror.go 的文件头注释。
//
// # 防变砖防线（每道都能单独中止，且都不破坏现有二进制）
//
//	防线 1  sha256 强制校验            传输截断/镜像投毒 → 删除 .part 报错
//	防线 2  下载大小与 Content-Length 比对   服务端/代理返回半截 body → 报错，不落目标
//	防线 3  换前跑新二进制自检（--version） 坏产物 / 架构不符 / 依赖缺失 → 不替换
//	防线 4  同目录 .new + rename       跨文件系统 rename 会失败；中途崩溃只留垃圾文件
//	防线 5  旧二进制改名备份 .old-<ver>  替换后仍可人工回滚；rename 失败时自动回滚
//	防线 6  权限不足直接报错            不尝试提权（sudo 提权会改属主，后患更大）
//
// # 与 npm 侧的差异（逐条，含一处**有意**保留的）
//
// 契约部分（镜像 / 拼接 / 去重 / direct 语义）与 npm/lib/mirror.js 逐条等价，
// mirror_test.go 的表驱动用例就是对照锚点。以下三处不同，都是刻意的：
//
//  1. SHA256SUMS.txt 校验：npm 是 best-effort（取不到就跳过），本包**强制**。
//     理由：npm 引导器失败的后果是「命令跑不起来，重跑一次即可」；GUI 自我
//     替换失败的后果是「用户点一下，应用再也打不开」，且没有命令行可退回。
//     请不要为了「统一」把这里改成 best-effort。
//  2. 断点续传：npm 侧一次把 body 收进内存后写 .part，没有续传；本包有
//     （`.part` + Range）。最终产物的可观测契约完全相同（同样的字节、同样的
//     校验），只是失败后能接着走——GUI 的下载被关窗/断网打断时这点很重要。
//  3. 校验和的来源：本包会**逐份尝试所有镜像**的 SHA256SUMS，任一份与本地
//     字节相符即通过。npm 侧只有一个来源。这不是分歧而是加强：它同时覆盖了
//     「镜像 txt 缓存落后于二进制」与「镜像不代理附件」两种真实情况。
//
// # 平台差异
//
// macOS：GUI 首次启动会 re-exec 到 ~/Applications/reply9842.app/Contents/MacOS/
// 的副本（见 cmd/gui/bundle_darwin.go），所以运行中进程的 os.Executable() 指向
// 的是 bundle 内的副本——SelfPath 解析出的就是它。**但只替换 bundle 副本是不够
// 的**：下次从裸二进制启动时 copyIfChanged 会按「源比副本新/大小不同」把旧版本
// 重新拷回 bundle，等于把更新回滚掉。正确做法见 SelfPath 的注释。
//
// Windows：正在运行的 .exe 不能删除，但 Vista+ 允许改名。所以流程是
// 「旧 → .old-<ver>，.new → 目标路径」；若改名被拒（旧系统 / 杀软锁），
// 返回可读错误并保留 .new，供下次启动或人工完成——绝不半途覆盖。
